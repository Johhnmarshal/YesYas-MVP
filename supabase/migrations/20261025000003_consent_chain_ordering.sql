--
-- The consent chain is built and read in two different orders, so the
-- verifier reports valid logs as tampered.
--
-- consent_events_chain() picks the previous event with
--   order by ce.created_at desc, ce.id desc limit 1
-- and lib/consent.ts reads the log back with
--   .order('created_at').order('id')
-- then checks events[i].prev_hash === events[i-1].payload_hash positionally.
--
-- created_at defaults to now(), which is the transaction timestamp and does
-- not advance within a transaction. trigger_reveal() writes three consent
-- rows in one statement, so all three share a created_at and the only
-- tie-break is id — a random v4 UUID. The chain is therefore built in
-- insertion order but read in random-UUID order, and the two coincide only by
-- luck.
--
-- Measured on the hosted project: for one couple's reveal, all 4 non-genesis
-- rows had a prev_hash pointing at a real row of the same user — the chain was
-- perfectly intact — while only 3 of 6 positions linked correctly when read in
-- (created_at, id) order. verifyConsentChain would have returned
-- { valid: false } and named a brokenAtId.
--
-- That is the worst failure this screen can have. Its entire purpose is to
-- prove the log has not been altered, and it would have accused the system of
-- altering it, in a product whose pitch is that the audit trail is
-- trustworthy.
--
-- Fix: give the table a monotonic insertion order that does not depend on
-- clock resolution or UUID luck, and use it on both sides.

alter table public.consent_events
  add column if not exists seq bigint generated by default as identity;

-- Backfill any existing rows deterministically before the column is relied on.
-- Ordering by (created_at, id) here is arbitrary for same-timestamp rows, but
-- those chains are already ambiguous; this at least freezes one order.
update public.consent_events c
set seq = ordered.rn
from (
  select id, row_number() over (order by created_at, id) as rn
  from public.consent_events
) ordered
where ordered.id = c.id
  and c.seq is null;

create unique index if not exists consent_events_seq_key
  on public.consent_events (seq);

create index if not exists consent_events_user_seq
  on public.consent_events (user_id, seq);

-- Chain against insertion order rather than timestamp-then-UUID.
create or replace function public.consent_events_chain()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_prev text;
  v_lock_key bigint;
begin
  if new.id is null then
    new.id := extensions.gen_random_uuid();
  end if;

  v_lock_key := pg_catalog.abs(pg_catalog.hashtext(new.user_id::text))::bigint;
  perform pg_catalog.pg_advisory_xact_lock(v_lock_key);

  -- seq is assigned from the identity sequence before this trigger runs, and
  -- increases with insertion, so it is a total order even for rows sharing a
  -- created_at.
  select ce.payload_hash
    into v_prev
  from public.consent_events ce
  where ce.user_id = new.user_id
  order by ce.seq desc
  limit 1;

  new.prev_hash := v_prev;
  new.payload_hash := pg_catalog.encode(
    extensions.digest(
      coalesce(new.id::text, '') ||
        '|' || new.event_type::text ||
        '|' || coalesce(new.payload::text, '') ||
        '|' || coalesce(new.prev_hash, ''),
      'sha256'
    ),
    'hex'
  );
  return new;
end;
$$;

revoke all on function public.consent_events_chain() from public, anon, authenticated;

comment on column public.consent_events.seq is
  'Monotonic insertion order. The hash chain is built and must be read in this order — created_at is the transaction timestamp and ties for rows written by the same statement.';
